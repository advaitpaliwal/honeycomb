package org.honeycomb.launcher.design

import android.content.Context
import android.content.res.Configuration
import android.os.Build
import androidx.compose.material3.ColorScheme
import androidx.compose.material3.contentColorFor
import androidx.compose.material3.dynamicDarkColorScheme
import androidx.compose.material3.dynamicLightColorScheme
import androidx.compose.runtime.getValue
import androidx.compose.runtime.mutableStateOf
import androidx.compose.runtime.setValue
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.isSpecified
import com.materialkolor.PaletteStyle
import com.materialkolor.dynamicColorScheme

/*
 * Honeycomb's colours (docs/design-language.md, Colour): Material 3 colour roles, never a hand-picked value. The phone's
 * own scheme comes first: Android 12 and later generate it from the wallpaper (dynamicDark/LightColorScheme), and
 * Honeycomb never overrides it. Only a phone that gives nothing (Android 11 and earlier) gets Honeycomb's own scheme,
 * generated by MaterialKolor (jordond/MaterialKolor, MIT; Google's material-color-utilities) from the icon's honey,
 * #FF9F0A, with the same TonalSpot style Android uses for wallpapers. Light or dark follows the system setting.
 */
object Native {
    /** The icon's honey: the seed when the phone has no scheme of its own. */
    val SEED = Color(0xFFFF9F0A)

    /** Honeycomb's own scheme from [SEED], light or [dark]. */
    fun honey(dark: Boolean): ColorScheme = dynamicColorScheme(SEED, isDark = dark, isAmoled = false, style = PaletteStyle.TonalSpot)

    /** The phone's scheme when it has one ([wallpaper]), else Honeycomb's honey scheme. */
    fun scheme(dark: Boolean, wallpaper: ColorScheme?): ColorScheme = wallpaper ?: honey(dark)

    /** Whether the system's dark theme is on. */
    fun isDark(ctx: Context): Boolean =
        ctx.resources.configuration.uiMode and Configuration.UI_MODE_NIGHT_MASK == Configuration.UI_MODE_NIGHT_YES

    /** The phone's wallpaper scheme on Android 12 and later; null where the phone has none. */
    fun wallpaper(ctx: Context, dark: Boolean): ColorScheme? = when {
        Build.VERSION.SDK_INT < Build.VERSION_CODES.S -> null
        dark -> dynamicDarkColorScheme(ctx)
        else -> dynamicLightColorScheme(ctx)
    }

    /** The scheme the phone asks for right now. */
    fun scheme(ctx: Context): ColorScheme = isDark(ctx).let { scheme(it, wallpaper(ctx, it)) }

    /** The ground under the grid, list and sheets: true black in dark mode (OLED), the scheme's surface in light. */
    fun ground(scheme: ColorScheme, dark: Boolean): Color = if (dark) Color.Black else scheme.surface
}

/**
 * The one way to colour UI: named roles over the current [ColorScheme]. [HoneycombTheme] publishes the scheme here, so
 * draw code and styles outside composition read the same roles. Reading a role inside composition subscribes to it.
 */
object HoneycombColors {
    var scheme: ColorScheme by mutableStateOf(Native.honey(dark = true))
        internal set
    var dark: Boolean by mutableStateOf(true)
        internal set

    /** The ground under the grid, list and sheets ([Native.ground]). */
    val background: Color get() = Native.ground(scheme, dark)

    /** The ground under a watch face: always black, as the faces are artwork drawn for it. */
    val faceGround: Color = Color.Black

    /** Sheets drawn over the face: Notification Centre and Control Centre (surface). */
    val sheet: Color get() = scheme.surface

    /** Cards: notifications, Smart Stack cards, settings and list rows (surfaceContainerHigh). */
    val platter: Color get() = scheme.surfaceContainerHigh

    /** The card edge under a notification pile's front card, one step down (surfaceContainer). */
    val pileSliver: Color get() = scheme.surfaceContainer

    /** Tiles and tonal controls at rest (surfaceContainerHighest). */
    val button: Color get() = scheme.surfaceContainerHighest

    /** Round controls at rest: back, transport, the notification x and bell (surfaceContainerHighest). */
    val circle: Color get() = scheme.surfaceContainerHighest

    val label: Color get() = scheme.onSurface

    /** Times, dates, subtitles (onSurfaceVariant). */
    val secondaryLabel: Color get() = scheme.onSurfaceVariant

    /** A switch's thumb when off, an outline (outline). */
    val outline: Color get() = scheme.outline

    /** The one accent: a control that is on, a progress fill, a primary action (primary). */
    val accent: Color get() = scheme.primary
    val onAccent: Color get() = scheme.onPrimary

    /** A quieter accent: icon discs, tonal buttons (secondaryContainer). */
    val tonal: Color get() = scheme.secondaryContainer
    val onTonal: Color get() = scheme.onSecondaryContainer

    /** Artwork placeholders such as album art (tertiaryContainer). */
    val artwork: Color get() = scheme.tertiaryContainer

    /** Something going wrong or being removed (error / errorContainer). */
    val error: Color get() = scheme.error
    val destructive: Color get() = scheme.errorContainer

    /** Dims content under a sheet (scrim at 60%). */
    val sheetDim: Color get() = scheme.scrim.copy(alpha = 0.6f)

    /** Fully opaque, for alpha masks (a DstIn fade keeps what it covers); never painted. */
    val maskOpaque: Color = Color.Black

    /** A pressed control darkens under this (M3's pressed state layer: on-surface at 10%). */
    val pressed: Color get() = scheme.onSurface.copy(alpha = 0.10f)

    /** The text and glyph colour that sits on [fill]: M3's pairing, on-surface for anything else. */
    fun contentFor(fill: Color): Color = scheme.contentColorFor(fill).takeIf { it.isSpecified } ?: label
}

/**
 * The face editor's fixed colour picks (FaceSwitcher's "Blue", "Mint" and "Pink"): seeds, never painted directly. A face
 * given one draws from a whole scheme generated from it (FacePalette.seeded), so it still works in light and dark. The
 * faces' default, and every other piece of artwork, reads the phone's scheme (Palettes.kt).
 */
object FaceSeeds {
    val blue = Color(0xFF6E8CFF)
    val mint = Color(0xFF00DAC3)
    val pink = Color(0xFFFDC0A8)
}
